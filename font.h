struct font
{
    s32 Ascent;
    s32 Descent;
    s32 GlyphCount;
    struct bitmap *Glyphs;
};

struct bitmap
GetGlyph(struct font Font, char Char)
{
    struct bitmap Glyph = {0};
    if (0 <= Char && Char < Font.GlyphCount)
    {
        Glyph = Font.Glyphs[Char];
    }
    return Glyph;
}

